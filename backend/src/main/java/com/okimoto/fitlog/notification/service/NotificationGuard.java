package com.okimoto.fitlog.notification.service;

/**
 * 通知を作る直前に、その通知がまだ正しいかを確かめる役（種類ごと）。
 *
 * <p>通知は保存の確定後に別のスレッドで作るので、フォローの直後にすぐ解除したときなどに、解除のあとで通知ができてしまう。それを防ぐため、
 * 取り消しのある操作（フォロー・ナイストレーニング・応援など）は、この役を用意する。
 *
 * <p>確かめるときは、もとの操作の行をロック（FOR SHARE）して読む。通知を作る部品は、確かめてから作り終えるまでを1つのトランザクションにするので、
 * 取り消し（行の削除と通知の削除）は通知ができるまで待つ。これで、取り消しと通知を作るのがどの順で起きても、取り消しのあとに通知が残らない
 */
public interface NotificationGuard {

  /** この種類の通知を確かめるか */
  boolean supports(String type);

  /** 通知がまだ正しいか（もとの操作が取り消されていないか） */
  boolean isStillValid(NotificationEvent event);
}
